// Builds src/data/campusPlaceIndex.json: every place on the 3D campus map (buildings, departments,
// hostels, gates, bus stops) with its map id and coordinates, small enough for the main bundle.
// The ride search, the route preview and the captain's Navigate button all look places up here,
// so any building on the map can be a pickup or drop. It also rewrites the campus_places list in
// supabase/schema.sql, which the database checks every ride's pickup and drop against.
//
//   node scripts/build-place-index.mjs   # re-run after build-campus-map.mjs
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { createServer } from 'vite';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// The map module imports JSON and three.js the Vite way, so load it through Vite's SSR loader
const server = await createServer({ root, server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
const { PLACES } = await server.ssrLoadModule('/src/components/campusMapWorld.js');
const { SPEC_TO_APP_ID } = await server.ssrLoadModule('/src/data/puAppleMap.js');

// Map metres back to latitude and longitude (the inverse of the spec's local projection)
const spec = JSON.parse(readFileSync(join(root, 'src/data/pu_apple_maps_reference.json'), 'utf8'));
const { origin_gps: ORIGIN, constants } = spec.metadata.coordinate_reference_system.local_cartesian_projection;
const round6 = (v) => Math.round(v * 1e6) / 1e6;

const places = PLACES.map((place) => ({
  id: place.id,
  name: place.name,
  // The short badge text, when it says something the full name doesn't (e.g. "Computer Science")
  ...(place.label && place.label !== place.name ? { label: place.label } : {}),
  kind: place.kind,
  lat: round6(ORIGIN.lat - place.z / constants.lat_to_meters),
  lng: round6(ORIGIN.lng + place.x / constants.lng_to_meters),
  ...(SPEC_TO_APP_ID[place.id] ? { appId: SPEC_TO_APP_ID[place.id] } : {}),
})).sort((a, b) => a.name.localeCompare(b.name));

writeFileSync(join(root, 'src/data/campusPlaceIndex.json'), JSON.stringify(places, null, 1) + '\n');
console.log(`campusPlaceIndex.json: ${places.length} places, ${places.filter((p) => p.appId).length} matched to the app's list`);

// The same names the app offers (src/lib/geo.js reads the index just written), for the database
const { CAMPUS_PLACES } = await server.ssrLoadModule('/src/lib/geo.js');
await server.close();
const sqlText = (text) => `'${text.replace(/'/g, "''")}'`;
const block = [
  '-- BEGIN campus places (generated by scripts/build-place-index.mjs; do not edit by hand)',
  'with incoming (name) as (values',
  CAMPUS_PLACES.map((place) => `  (${sqlText(place.name)})`).join(',\n'),
  '), added as (',
  '  insert into public.campus_places (name) select name from incoming on conflict (name) do nothing',
  ')',
  'delete from public.campus_places where name not in (select name from incoming);',
  '-- END campus places',
].join('\n');
const schemaPath = join(root, 'supabase/schema.sql');
const schema = readFileSync(schemaPath, 'utf8');
const pattern = /-- BEGIN campus places[\s\S]*?-- END campus places/;
if (!pattern.test(schema)) throw new Error('campus places block not found in supabase/schema.sql');
writeFileSync(schemaPath, schema.replace(pattern, block));
console.log(`schema.sql: ${CAMPUS_PLACES.length} campus places`);
